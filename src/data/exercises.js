/*
 * exercises.js
 *
 * The whole exercise catalog lives here, as plain data. Nothing in this file
 * draws anything or talks to a server: screens import these arrays and decide
 * how to show them.
 *
 * What you will find, top to bottom:
 *   1. DISCIPLINES: gym, yoga, Animal Flow, Jiu Jitsu (the second axis).
 *      GROUPS: the muscle groups, in the order they appear as filter chips.
 *      VUELTAS: fixed sequences (INCA's four core circuits); each one is
 *      also a routine in routines.js.
 *   2. EXERCISES: one object per exercise (shape explained right below).
 *      The list is written as RAW_EXERCISES and passed through
 *      normalizeExercise(), which fills the defaults (discipline "gym").
 *   3. Small helper functions so screens can look things up by id or key.
 *
 * Shape of one exercise:
 *   id            unique kebab-case key, used in URLs and in "alternatives"
 *   name          what you see on screen
 *   originalName  OPTIONAL. Original name (Sanskrit, English), shown smaller
 *   discipline    one of the DISCIPLINES keys. Defaults to "gym", so gym
 *                 entries leave it out
 *   group         main muscle group (one of the GROUPS keys)
 *   secondary     optional extra groups it also works
 *   pattern       movement family (squat, hinge, row...), groups similar exercises.
 *                 The animation itself lives in src/animations/exercises/<id>.js
 *   equipment     free text tags, also used by the search box
 *   description   1 or 2 sentences: what it is and what it trains
 *   cues          technique notes, imperative voseo ("bajá", "apretá")
 *   prescription  reps, sets, rest, tempo
 *   alternatives  ids of exercises to do instead when the gym is crowded
 *   youtubeQuery  search text for the "Ver en YouTube" link
 *   source        "trainer" = from the coach's notes, "added" = suggested extra,
 *                 "research" = added from outside sources (new disciplines)
 *   vuelta        OPTIONAL. Key of the VUELTAS sequence it belongs to
 *   measure       OPTIONAL. What the workout log asks for: "reps", "secs"
 *                 (isometric holds) or "mins" (continuous cardio; the log
 *                 asks for minutes and the database keeps them as seconds).
 *                 Without it the log asks for kg and reps.
 *   stretches     OPTIONAL. Ids of stretches to do afterwards ("Estirá después")
 *   routineLink   OPTIONAL. Id of a routine the detail page links to
 *   anim          OPTIONAL. Reuse or adjust an animation instead of having a
 *                 file of its own: { from, hold, bare }
 *                   from     id of the exercise whose animation file to use
 *                   hold     stay in the spec's held pose, with a slow
 *                            breathing pulse (static yoga holds)
 *                   bare     hide the equipment (bars, dumbbells, benches)
 *
 * To add an exercise: copy any block, give it a new id, and run
 * `node scripts/check-data.mjs` to make sure every reference still exists.
 */

