/*
 * exercises.js
 *
 * The whole exercise catalog lives here, as plain data. Nothing in this file
 * draws anything or talks to a server: screens import these arrays and decide
 * how to show them.
 *
 * What you will find, top to bottom:
 *   1. GROUPS: the muscle groups, in the order they appear as filter chips.
 *   2. EXERCISES: one object per exercise (shape explained right below).
 *   3. Small helper functions so screens can look things up by id or key.
 *
 * Shape of one exercise:
 *   id            unique kebab-case key, used in URLs and in "alternatives"
 *   name          what you see on screen
 *   group         main muscle group (one of the GROUPS keys)
 *   secondary     optional extra groups it also works
 *   pattern       movement pattern; picks which stick-figure animation to show
 *   equipment     free text tags, also used by the search box
 *   description   1 or 2 sentences: what it is and what it trains
 *   cues          technique notes, imperative voseo ("bajá", "apretá")
 *   prescription  reps, sets, rest, tempo
 *   alternatives  ids of exercises to do instead when the gym is crowded
 *   youtubeQuery  search text for the "Ver en YouTube" link
 *   source        "trainer" = from the coach's notes, "added" = suggested extra
 *
 * To add an exercise: copy any block, give it a new id, and run
 * `node scripts/check-data.mjs` to make sure every reference still exists.
 */

