/*
 * "Estirá después" for gym exercises, by muscle group: the yoga stretches
 * that suit the muscles a gym exercise works. An exercise that lists its
 * own `stretches` keeps those instead.
 */
const STRETCHES_BY_GROUP = {
  isquios: ["yoga-pinza-de-pie", "yoga-pinza-sentada", "yoga-perro-abajo"],
  cuadriceps: ["yoga-heroe", "yoga-zancada-baja", "yoga-camello"],
  gluteos: ["yoga-paloma", "yoga-mariposa", "yoga-guirnalda"],
  cadera: ["yoga-zancada-baja", "yoga-lagarto", "yoga-paloma"],
  columna: ["yoga-gato-vaca", "yoga-nino", "yoga-torsion-acostado"],
};

/*
 * Fills the defaults, so entries only write what is special about them:
 * discipline "gym" (all the original exercises leave it out) and, for gym
 * exercises, the "Estirá después" list of their muscle group.
 */
function normalizeExercise(ex) {
  const discipline = ex.discipline ?? "gym";
  const stretches = ex.stretches ?? (discipline === "gym" ? STRETCHES_BY_GROUP[ex.group] : undefined);
  return { ...ex, discipline, ...(stretches ? { stretches } : {}) };
}

export const EXERCISES = RAW_EXERCISES.map(normalizeExercise);

/* ------------------------------------------------------------------ */
/* 3. Lookup helpers                                                   */
/* ------------------------------------------------------------------ */

// Builds a dictionary { id: exercise } once, so finding by id is instant.
const EXERCISES_BY_ID = Object.fromEntries(EXERCISES.map((ex) => [ex.id, ex]));

// Same idea for group labels: { "core": "Abdomen y core", ... }
const GROUP_LABELS = Object.fromEntries(GROUPS.map((g) => [g.key, g.label]));

// Returns the exercise with that id, or undefined if it does not exist.
export function getExercise(id) {
  return EXERCISES_BY_ID[id];
}

// Returns the vuelta with that key ("pelota" -> { label, chip, routineId }), or undefined.
export function getVuelta(key) {
  return VUELTAS.find((v) => v.key === key);
}

// Returns the Spanish label for a discipline key ("animal-flow" -> "Animal Flow").
const DISCIPLINE_LABELS = Object.fromEntries(DISCIPLINES.map((d) => [d.key, d.label]));
export function disciplineLabel(key) {
  return DISCIPLINE_LABELS[key] ?? key;
}

// Returns the Spanish label for a group key ("core" -> "Abdomen y core").
export function groupLabel(key) {
  return GROUP_LABELS[key] ?? key;
}
